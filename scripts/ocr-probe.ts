import { createWorker } from 'tesseract.js';
import { createCanvas, loadImage } from '@napi-rs/canvas';
import { writeFileSync } from 'node:fs';
const t0 = Date.now();
const img = await loadImage('/home/claude/elin-v2/work/orig-000.jpg');
const S = 2;
const c = createCanvas(img.width * S, img.height * S);
const g = c.getContext('2d');
g.imageSmoothingQuality = 'high';
g.drawImage(img, 0, 0, img.width * S, img.height * S);
const buf = c.toBuffer('image/png');
const w = await createWorker(['swe', 'eng'], 1, { langPath: '/home/claude/elin-v2/app/public/tessdata', cacheMethod: 'none', gzip: true } as any);
await w.setParameters({ tessedit_pageseg_mode: '11' as any, preserve_interword_spaces: '1' });
const r = await w.recognize(buf, {}, { blocks: true });
const lines: any[] = [];
for (const b of r.data.blocks ?? []) for (const p of b.paragraphs) for (const l of p.lines) lines.push({ text: l.text.trim(), conf: Math.round(l.confidence), bbox: [l.bbox.x0 / S, l.bbox.y0 / S, l.bbox.x1 / S, l.bbox.y1 / S].map(Math.round) });
writeFileSync('/home/claude/elin-v2/work/ocr.json', JSON.stringify(lines, null, 1));
console.log(lines.length, 'lines', Date.now() - t0, 'ms');
for (const l of lines) console.log(l.conf, l.bbox.join(','), l.text);
await w.terminate();
