// Real browser test: login, open PDF, wait for OCR, mark the front name, ask, wait, download.
import { createRequire } from 'node:module';
const { chromium } = createRequire('/home/claude/.npm-global/lib/node_modules/')('playwright');
const BASE = 'http://localhost:5199';
const shots = '/home/claude/elin-v2/work/e2e';
import { mkdirSync, writeFileSync } from 'node:fs';
mkdirSync(shots, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
page.on('console', (m) => { if (m.type() === 'error') console.log('console error:', m.text().slice(0, 300)); });
page.on('pageerror', (e) => console.log('page error:', e.message));
const t0 = Date.now();
await page.goto(BASE + '/');
await page.fill('#pw', 'test-losen');
await page.click('#b');
await page.waitForSelector('.drop', { timeout: 30000 });
await page.screenshot({ path: shots + '/1-start.png' });
await page.setInputFiles('.drop input', '/home/claude/elin-v2/samples/original.pdf');
await page.waitForSelector('.msg.assistant', { timeout: 240000 });
console.log('opened + OCR', ((Date.now() - t0) / 1000).toFixed(1), 's');
await page.screenshot({ path: shots + '/2-open.png' });
// mark the front "MARIA" (image px ~ 365..475 x 375..408)
const stage = await page.locator('.stage').boundingBox();
const W = 1672, H = 941;
const p = (x, y) => [stage.x + (x / W) * stage.width, stage.y + (y / H) * stage.height];
const [ax, ay] = p(355, 370), [bx, by] = p(485, 410);
await page.mouse.move(ax, ay); await page.mouse.down(); await page.mouse.move(bx, by, { steps: 8 }); await page.mouse.up();
await page.fill('#msg', 'Byt namnet till SOFIA här');
const t1 = Date.now();
await page.click('form button.primary');
await page.waitForFunction(() => document.querySelectorAll('.msg.assistant').length >= 2 || document.querySelector('.error'), null, { timeout: 300000 });
console.log('edit', ((Date.now() - t1) / 1000).toFixed(1), 's');
console.log('reply:', await page.locator('.msg.assistant').last().innerText().catch(() => ''));
console.log('error:', await page.locator('.error').innerText().catch(() => '-'));
await page.screenshot({ path: shots + '/3-after.png' });
await page.click('text=Sida vid sida');
await page.screenshot({ path: shots + '/4-both.png' });
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('text=Ladda ner PDF')]);
await dl.saveAs(shots + '/result.pdf');
console.log('downloaded', dl.suggestedFilename());
await page.setViewportSize({ width: 400, height: 860 });
await page.screenshot({ path: shots + '/5-phone.png' });
await browser.close();
